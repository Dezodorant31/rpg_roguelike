// ---------------------------------------------------------------------------
// Behavior — интерфейс стратегии поведения монстра.
//
// Strategy из списка паттернов: «семейство алгоритмов, инкапсулированных
// в объектах, которые можно заменять друг другом».
//
// Здесь: один ход монстра. Что именно делать — решает конкретная стратегия.
// EnemyTurnState не знает, «агрессивный» монстр или «трус» — он просто
// вызывает takeTurn у поведения, которое нашёл по behaviorId.
//
// Почему takeTurn возвращает void, а не bool:
//   - ход монстра «потрачен» всегда (он либо сдвинулся, либо атаковал,
//     либо подождал — это уже ход). В отличие от игрока, у которого
//     «нажал в стену» = ход не потрачен;
//   - если понадобится «монстр не потратил ход» (например, парализован),
//     это решается внутри поведения, а не сигнатурой.
//
// Почему параметры — ссылки, а не GameContext:
//   - Behavior не нужен весь контекст (log, player) — только то, что
//     реально используется. Это упрощает тесты: можно подсунуть World и Map
//     без MessageLog, если поведение не логирует.
//   - Если завтра понадобится rng — добавим параметр.
// ---------------------------------------------------------------------------
class Behavior
{
public:
    virtual ~Behavior() = default;

    virtual void takeTurn(World& world,
                          Map& map,
                          EntityId self,
                          EntityId player,
                          const MonsterType& type,
                          MessageLog& log) const = 0;

    [[nodiscard]] virtual const char* name() const = 0;
};
