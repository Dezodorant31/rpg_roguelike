#pragma once

#include "data/MonsterType.hpp"

// ---------------------------------------------------------------------------
// MonsterTypeRef — компонент «этот монстр — гоблин».
//
// Хранит ПРЯМУЮ ССЫЛКУ (указатель) на MonsterType, а не копию.
// MonsterType живёт в MonsterTypeRegistry, который создаётся в main
// до спавна монстров и живёт весь сеанс. Указатель валиден, пока жив
// реестр. Копия была бы дороже (sf::Color + 3 std::string) и требовала
// синхронизации при изменении типа.
//
// Почему указатель, а не std::string id:
//   - каждый ход монстра ищем MonsterType по id в unordered_map —
//     лишний lookup. Указатель — прямой доступ;
//   - риск «висячего» указателя есть, но реестр переживает всех монстров
//     по дизайну (создаётся раньше, умирает позже).
//
// Если захочешь строгости — можно заменить на std::string id + поиск в
// реестре в EnemyTurnState. Медленнее, но безопаснее. Пока — указатель.
// ---------------------------------------------------------------------------
struct MonsterTypeRef
{
    const MonsterType* type = nullptr;
};
