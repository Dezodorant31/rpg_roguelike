#pragma once

#include "world/DungeonBuilder.hpp"
#include "world/Rect.hpp"

#include <cstdint>
#include <deque>
#include <random>

// ---------------------------------------------------------------------------
// BSPDungeonBuilder — генерация подземелья через Binary Space Partitioning.
//
// Идея:
//   1. Всё пространство карты (внутри рамки) — один «лист».
//   2. Рекурсивно делим лист пополам (вертикально/горизонтально),
//      пока лист не станет маленьким.
//   3. В каждом листе ставим комнату — подпрямоугольник с отступом.
//   4. Соединяем соседние комнаты L-коридорами.
//   5. Гарантируем связность: из точки спавна можно дойти до всех комнат.
//
// Детерминизм: один seed → одна и та же карта. Это критично
// для воспроизводимости багов и для тестов.
// ---------------------------------------------------------------------------
class BSPDungeonBuilder final : public DungeonBuilder
{
public:
    [[nodiscard]] Dungeon build(std::uint32_t seed,
                                int width, int height) override;

private:
    // -----------------------------------------------------------------------
    // Узел BSP-дерева.
    //
    // Хранится в std::deque<Node> внутри build(). Указатели left/right —
    // «ссылки» на элементы того же deque. Почему deque, а не vector:
    //   - deque НЕ инвалидирует указатели/ссылки при push_back на конце;
    //   - vector — инвалидирует (реаллокация).
    // Нам критична стабильность, потому что дерево ссылается само на себя.
    // -----------------------------------------------------------------------
    struct Node
    {
        Rect bounds;                       // прямоугольник узла

        Node* left  = nullptr;             // левый ребёнок (или nullptr)
        Node* right = nullptr;             // правый ребёнок (или nullptr)

        bool hasRoom    = false;           // в этом листе есть комната?
        Rect roomBounds;                   // прямоугольник комнаты (если hasRoom)

        [[nodiscard]] bool isLeaf() const noexcept
        {
            return left == nullptr && right == nullptr;
        }
    };

    // -----------------------------------------------------------------------
    // Рекурсивно делим узел. Создаёт left/right и вызывает себя для них.
    // nodes — контейнер всех узлов (deque, чтобы Node* были стабильны).
    // -----------------------------------------------------------------------
    void splitNode(std::deque<Node>& nodes,
                   Node& node,
                   std::mt19937& rng,
                   int depth);

    // -----------------------------------------------------------------------
    // В каждом листе создаём комнату (подпрямоугольник) и прорубаем пол.
    // Рекурсивно обходит всё дерево.
    // -----------------------------------------------------------------------
    void createRooms(Node& node,
                     std::mt19937& rng,
                     Dungeon& dungeon);

    // -----------------------------------------------------------------------
    // Соединяем комнаты коридорами. Для каждого внутреннего узла берём
    // центры комнат левого и правого поддеревьев и прорубаем L-коридор.
    // Рекурсивно обходит всё дерево.
    // -----------------------------------------------------------------------
    void connectNodes(Node& node,
                      std::mt19937& rng,
                      Dungeon& dungeon);

    // -----------------------------------------------------------------------
    // L-коридор между двумя точками. Случайно выбирает порядок:
    // сначала по X или сначала по Y.
    // -----------------------------------------------------------------------
    static void carveCorridor(Dungeon& dungeon,
                              int x1, int y1,
                              int x2, int y2,
                              std::mt19937& rng);

    // -----------------------------------------------------------------------
    // Найти центр комнаты в поддереве узла.
    // Возвращает false, если в поддереве нет ни одной комнаты.
    // Через out-параметры — чтобы не тащить std::optional в рекурсию.
    // -----------------------------------------------------------------------
    [[nodiscard]] static bool findRoomCenter(const Node& node,
                                             int& outX, int& outY);
};
